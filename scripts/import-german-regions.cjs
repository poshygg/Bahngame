const fs = require('node:fs/promises');
const path = require('node:path');

const source = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces.geojson';
const mercator = ([lon, lat]) => [lon * Math.PI / 180, Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360))];
function simplify(points, tolerance = 0.000035) {
  if (points.length < 4) return points;
  const first = points[0], last = points[points.length - 1];
  const dx = last[0] - first[0], dy = last[1] - first[1];
  let maximum = 0, index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const t = Math.max(0, Math.min(1, ((points[i][0] - first[0]) * dx + (points[i][1] - first[1]) * dy) / (dx * dx + dy * dy || 1)));
    const distance = Math.hypot(points[i][0] - first[0] - t * dx, points[i][1] - first[1] - t * dy);
    if (distance > maximum) { maximum = distance; index = i; }
  }
  return maximum > tolerance
    ? [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
    : [first, last];
}
async function main() {
  const root = path.resolve(__dirname, '..');
  let raw;
  if (process.argv.includes('--cached')) raw = JSON.parse(await fs.readFile(path.join(root, 'artifacts/german-regions.geojson'), 'utf8'));
  else {
    const response = await fetch(source);
    if (!response.ok) throw new Error(`Natural Earth: ${response.status}`);
    raw = await response.json();
  }
  const features = raw.features.filter(f => f.properties.adm0_a3 === 'DEU');
  if (features.length !== 16) throw new Error(`Expected 16 German regions, found ${features.length}`);
  await fs.mkdir(path.join(root, 'artifacts'), { recursive: true });
  await fs.writeFile(path.join(root, 'artifacts/german-regions.geojson'), JSON.stringify({ type: 'FeatureCollection', features }));
  const ringsOf = feature => (feature.geometry.type === 'MultiPolygon' ? feature.geometry.coordinates : [feature.geometry.coordinates]).map(polygon => polygon[0]);
  const all = features.flatMap(ringsOf).flat().map(mercator);
  const minX = Math.min(...all.map(p => p[0])), maxX = Math.max(...all.map(p => p[0]));
  const minY = Math.min(...all.map(p => p[1])), maxY = Math.max(...all.map(p => p[1]));
  const scale = Math.min(460 / (maxX - minX), 600 / (maxY - minY));
  const offsetX = (500 - (maxX - minX) * scale) / 2;
  const offsetY = (640 - (maxY - minY) * scale) / 2;
  const project = p => ({ x: offsetX + (p[0] - minX) * scale, y: offsetY + (maxY - p[1]) * scale });
  const regions = features.map(feature => {
    const p = feature.properties;
    const coordinate = { longitude: Number(p.longitude), latitude: Number(p.latitude) };
    return {
      id: p.iso_3166_2,
      name: { en: p.name_en || p.name, de: p.name_de || p.name },
      shortName: p.iso_3166_2.split('-')[1],
      coordinate,
      labelPoint: project(mercator([coordinate.longitude, coordinate.latitude])),
      paths: ringsOf(feature).filter(ring => ring.length >= 4).map(ring => simplify(ring.map(mercator)).map(project).map((point, index) => `${index ? 'L' : 'M'}${point.x.toFixed(2)},${point.y.toFixed(2)}`).join(' ') + ' Z'),
    };
  }).sort((a, b) => a.id.localeCompare(b.id));
  const header = `import type { GeoPoint } from './geography';\nimport type { Localized } from './types';\n\n/** Natural Earth 1:10m admin-1 boundaries, public domain. Generated by scripts/import-german-regions.cjs. */\nexport type GermanRegion = { id: string; name: Localized; shortName: string; coordinate: GeoPoint; labelPoint: { x: number; y: number }; paths: string[] };\nexport const GERMANY_MAP_VIEWBOX = '0 0 500 640';\nexport const GERMAN_REGIONS: GermanRegion[] = `;
  const projectCode = `;\nexport function projectGermanyPoint(point: GeoPoint) {\n  const x = point.longitude * Math.PI / 180;\n  const y = Math.log(Math.tan(Math.PI / 4 + point.latitude * Math.PI / 360));\n  return { x: ${offsetX} + (x - ${minX}) * ${scale}, y: ${offsetY} + (${maxY} - y) * ${scale} };\n}\n`;
  await fs.writeFile(path.join(root, 'src/data/germany-regions.ts'), header + JSON.stringify(regions, null, 2) + projectCode);
  console.log(JSON.stringify({ regions: regions.length, ids: regions.map(r => r.id), source }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
